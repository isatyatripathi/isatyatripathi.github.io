import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function resolveTailwind() {
  try {
    return require.resolve("tailwindcss");
  } catch {
    return "/opt/nvm/versions/node/v22.16.0/lib/node_modules/tailwindcss/dist/lib.js";
  }
}

const tailwindEntry = resolveTailwind();
const { compile } = require(tailwindEntry);
const packageRoot = path.resolve(path.dirname(tailwindEntry), "..");
const defaultTheme = fs.readFileSync(path.join(packageRoot, "theme.css"), "utf8");
const preflight = fs.readFileSync(path.join(packageRoot, "preflight.css"), "utf8");
const customSource = fs.readFileSync(path.join(root, "styles", "tailwind-source.css"), "utf8");

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(fullPath);
    return /\.(tsx?|mdx?)$/.test(entry.name) ? [fullPath] : [];
  });
}

const candidates = new Set([
  "min-h-screen",
  "antialiased",
  "relative",
  "overflow-hidden",
  "z-10",
  "flex",
  "flex-wrap",
  "items-center",
  "gap-3",
]);

for (const file of [...walk(path.join(root, "app")), ...walk(path.join(root, "components"))]) {
  const source = fs.readFileSync(file, "utf8");
  const literalPattern = /className\s*=\s*(?:"([^"]+)"|'([^']+)'|\{`([^`]+)`\})/g;
  for (const match of source.matchAll(literalPattern)) {
    const value = match[1] ?? match[2] ?? match[3] ?? "";
    for (const token of value.replace(/\$\{[^}]+\}/g, " ").split(/\s+/)) {
      if (/^[!a-zA-Z0-9_:[\]./\-]+$/.test(token)) candidates.add(token);
    }
  }
}

const source = `${defaultTheme}\n${preflight}\n${customSource}`;
const compiled = await compile(source);
const css = compiled.build([...candidates].sort());
const banner = "/* Generated by scripts/build-tailwind.mjs. Do not edit directly. */\n";
fs.writeFileSync(path.join(root, "app", "tailwind.generated.css"), banner + css);
console.log(`Generated Tailwind CSS with ${candidates.size} candidates.`);
